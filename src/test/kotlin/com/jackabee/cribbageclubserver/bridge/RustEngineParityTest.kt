package com.jackabee.cribbageclubserver.bridge

import com.fasterxml.jackson.databind.DeserializationFeature
import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule
import com.fasterxml.jackson.module.kotlin.jacksonObjectMapper
import com.fasterxml.jackson.module.kotlin.readValue
import com.jackabee.cribbageclubserver.model.action.GameAction
import com.jackabee.cribbageclubserver.model.card.Card
import com.jackabee.cribbageclubserver.model.card.Rank
import com.jackabee.cribbageclubserver.model.game.GameStage
import com.jackabee.cribbageclubserver.model.game.GameState
import org.junit.jupiter.api.BeforeAll
import org.junit.jupiter.api.Test
import java.io.File
import kotlin.test.assertEquals

/**
 * Cross-platform parity test verifying the Kotlin/JNA bridge produces
 * identical game states as the Rust engine for deterministic scenarios.
 *
 * Reads the same fixture file generated by `engine/tests/generate_fixtures.rs`.
 */
class RustEngineParityTest {

    companion object {
        private lateinit var lib: CribbageEngineLib
        private lateinit var objectMapper: ObjectMapper
        private lateinit var adapter: RustEngineAdapter
        private lateinit var fixture: Map<String, Any>

        @JvmStatic
        @BeforeAll
        fun setup() {
            lib = CribbageEngineLib.load()
            objectMapper = jacksonObjectMapper()
                .registerModule(JavaTimeModule())
                .configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false)
            adapter = RustEngineAdapter(lib, objectMapper)

            val fixtureFile = File("engine/tests/fixtures/game_scenarios.json")
            fixture = objectMapper.readValue(fixtureFile)
        }
    }

    @Suppress("UNCHECKED_CAST")
    private fun getScenario(): Map<String, Any> {
        val scenarios = fixture["scenarios"] as List<Map<String, Any>>
        return scenarios[0]
    }

    @Suppress("UNCHECKED_CAST")
    private fun getSnapshots(): Map<String, Any> {
        return getScenario()["snapshots"] as Map<String, Any>
    }

    private fun parseSnapshotState(snapshots: Map<String, Any>, key: String): GameState {
        val json = objectMapper.writeValueAsString(snapshots[key])
        return objectMapper.readValue(json, GameState::class.java)
    }

    private fun assertStateMatches(actual: GameState, expected: GameState, checkpoint: String) {
        assertEquals(expected.stage, actual.stage, "Stage mismatch at $checkpoint")
        assertEquals(expected.players.size, actual.players.size, "Player count mismatch at $checkpoint")

        for (i in expected.players.indices) {
            val ep = expected.players[i]
            val ap = actual.players[i]
            assertEquals(ep.id, ap.id, "Player $i ID mismatch at $checkpoint")
            assertEquals(ep.hand.size, ap.hand.size, "Player $i hand size mismatch at $checkpoint")
            assertEquals(ep.score, ap.score, "Player $i score mismatch at $checkpoint")
            assertEquals(ep.hand, ap.hand, "Player $i hand mismatch at $checkpoint")
        }

        assertEquals(expected.crib.size, actual.crib.size, "Crib size mismatch at $checkpoint")
        assertEquals(expected.crib, actual.crib, "Crib contents mismatch at $checkpoint")
        assertEquals(expected.cutCard, actual.cutCard, "Cut card mismatch at $checkpoint")
        assertEquals(expected.peggingCount, actual.peggingCount, "Pegging count mismatch at $checkpoint")
        assertEquals(expected.dealerIndex, actual.dealerIndex, "Dealer index mismatch at $checkpoint")
    }

    @Test
    fun `parity - seed 42 full round through JNA`() {
        val scenario = getScenario()
        val seed = (scenario["seed"] as Number).toLong()
        val snapshots = getSnapshots()

        // Create seeded engine via JNA
        val (engine, _) = adapter.createSeededEngine(
            "parity_test_1", "p1", "Player 1", "p2", "Player 2", seed
        )

        engine.use { eng ->
            // Checkpoint: after_deal
            val afterDeal = adapter.getState(eng)
            val expectedDeal = parseSnapshotState(snapshots, "after_deal")
            assertStateMatches(afterDeal, expectedDeal, "after_deal")

            // Discard first two cards from each player
            val p1Discards = afterDeal.players[0].hand.take(2)
            val p2Discards = afterDeal.players[1].hand.take(2)

            for (card in p1Discards) {
                adapter.applyAction(eng, GameAction.DiscardToCrib("p1", card))
            }
            for (card in p2Discards) {
                adapter.applyAction(eng, GameAction.DiscardToCrib("p2", card))
            }

            // Checkpoint: after_discard
            val afterDiscard = adapter.getState(eng)
            val expectedDiscard = parseSnapshotState(snapshots, "after_discard")
            assertStateMatches(afterDiscard, expectedDiscard, "after_discard")

            // Cut
            val cutter = afterDiscard.currentPlayerId!!
            adapter.applyAction(eng, GameAction.CutDeck(cutter))

            // Checkpoint: after_cut
            val afterCut = adapter.getState(eng)
            val expectedCut = parseSnapshotState(snapshots, "after_cut")
            assertStateMatches(afterCut, expectedCut, "after_cut")

            // Pegging — play lowest legal card or say Go
            for (iteration in 0 until 20) {
                val state = adapter.getState(eng)
                if (state.stage != GameStage.PEGGING) break

                val currentId = state.currentPlayerId!!
                val player = state.players.first { it.id == currentId }
                val playable = player.hand
                    .filter { state.peggingCount + it.peggingValue() <= 31 }
                    .minByOrNull { it.peggingValue() }

                if (playable != null) {
                    adapter.applyAction(eng, GameAction.PlayCard(currentId, playable))
                } else {
                    adapter.applyAction(eng, GameAction.Go(currentId))
                }
            }

            // Checkpoint: after_pegging
            val afterPegging = adapter.getState(eng)
            val expectedPegging = parseSnapshotState(snapshots, "after_pegging")
            assertStateMatches(afterPegging, expectedPegging, "after_pegging")

            // Counting
            for (iteration in 0 until 3) {
                val state = adapter.getState(eng)
                if (state.stage != GameStage.COUNTING) break
                val counter = state.currentPlayerId!!
                adapter.applyAction(eng, GameAction.CountHand(counter))
            }

            // Checkpoint: after_counting (scores only)
            val finalState = adapter.getState(eng)
            val expectedScores = snapshots["after_counting"] as Map<*, *>
            assertEquals(
                (expectedScores["p1_score"] as Number).toInt(),
                finalState.players[0].score,
                "P1 final score mismatch"
            )
            assertEquals(
                (expectedScores["p2_score"] as Number).toInt(),
                finalState.players[1].score,
                "P2 final score mismatch"
            )
        }
    }

    /** Card pegging value: face cards = 10, Ace = 1, others = ordinal + 1. */
    private fun Card.peggingValue(): Int = when (rank) {
        Rank.ACE -> 1
        Rank.JACK, Rank.QUEEN, Rank.KING -> 10
        else -> rank.ordinal + 1
    }

    @Test
    fun `parity - JSON round trip through JNA`() {
        val snapshots = getSnapshots()

        for (name in listOf("after_deal", "after_discard", "after_cut", "after_pegging")) {
            val json = objectMapper.writeValueAsString(snapshots[name])
            val state = objectMapper.readValue(json, GameState::class.java)
            val reJson = objectMapper.writeValueAsString(state)
            val reState = objectMapper.readValue(reJson, GameState::class.java)

            assertEquals(state.stage, reState.stage, "Round-trip stage mismatch for $name")
            assertEquals(state.players, reState.players, "Round-trip players mismatch for $name")
            assertEquals(state.crib, reState.crib, "Round-trip crib mismatch for $name")
            assertEquals(state.cutCard, reState.cutCard, "Round-trip cutCard mismatch for $name")
        }
    }
}
